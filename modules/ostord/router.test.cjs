const assert=require('node:assert/strict');
require('./router.js');
const classify=globalThis.BudUncontestedRouter.classify;
assert.equal(classify([]).module,'opening');
assert.equal(classify(['1H']).module,'responses-1-major');
assert.equal(classify(['1C']).module,'responses-1-minor');
assert.equal(classify(['1H','2N']).module,'stenberg');
assert.equal(classify(['1H','2N','3H']).module,'stenberg');
assert.equal(classify(['1S','1N']).module,'rebid-nt-response');
assert.equal(classify(['1S','1N','2N']).module,'responder-continuation-nt');
assert.equal(classify(['1N']).module,'responses-1nt');
assert.equal(classify(['1N','2C']).module,'stayman');
assert.equal(classify(['1N','2C','2D','2H']).module,'stayman');
assert.equal(classify(['1N','2D']).module,'transfer');
assert.equal(classify(['1N','2D','2H','2N']).module,'transfer');
assert.equal(classify(['2N']).module,'responses-2nt');
assert.equal(classify(['2N','3C']).module,'stayman-2nt');
assert.equal(classify(['2N','3D']).module,'transfer-2nt');
assert.equal(classify(['1H','2H']).module,'trumfstod');
assert.equal(classify(['1C','2C']).module,'trumfstod');
assert.equal(classify(['1H','2D']).module,'rebid-1-over-2');
assert.equal(classify(['1H','2C']).module,'rebid-2-over-1');
assert.equal(classify(['1H','1S','2D']).module,'responder-continuation-suit');
assert.equal(classify(['1H','2C','2H']).module,'responder-continuation-suit');
assert.equal(classify(['1H','1S','4N']).module,'slam');
assert.equal(classify(['1H','2H','3H','4N']).module,'slam');
assert.equal(classify(['1H','X']).module,'out-of-scope');
assert.equal(classify(['1H','P','1S','P','2N']).module,'responder-continuation-nt');
console.log('Router tests passed');
